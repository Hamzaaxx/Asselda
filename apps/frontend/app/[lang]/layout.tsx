import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { Source_Sans_3, Source_Serif_4, Noto_Kufi_Arabic, Noto_Sans_Arabic } from "next/font/google";

import "@/styles/globals.css";

import {
	getDirection,
	isLocale,
	localeTags,
	locales,
	localizePath,
	type Locale,
} from "@/lib/i18n/config";
import { getDictionary } from "@/lib/i18n";
import { Header } from "@/components/layout/Header";
import { Footer } from "@/components/layout/Footer";

/*
 * Fonts.
 *
 * Four faces, all self-hosted by next/font — the previous implementation loaded
 * next/font *and* a render-blocking Google Fonts @import, and applied two
 * `.className` values to the same element so one silently overrode the other.
 *
 * Only `.variable` is used here: the families are selected in CSS, which lets
 * Arabic pages switch stacks without a class change on every element.
 */
const latinSans = Source_Sans_3({
	subsets: ["latin", "latin-ext"],
	variable: "--font-latin-sans",
	display: "swap",
});

const latinSerif = Source_Serif_4({
	subsets: ["latin", "latin-ext"],
	variable: "--font-latin-serif",
	display: "swap",
});

const arabicSans = Noto_Sans_Arabic({
	subsets: ["arabic"],
	variable: "--font-arabic-sans",
	display: "swap",
});

const arabicDisplay = Noto_Kufi_Arabic({
	subsets: ["arabic"],
	variable: "--font-arabic-display",
	display: "swap",
});

const fontVariables = [
	latinSans.variable,
	latinSerif.variable,
	arabicSans.variable,
	arabicDisplay.variable,
].join(" ");

/*
 * Locale params are generated by each page rather than here.
 *
 * A layout-level generateStaticParams suppresses the one on a nested dynamic
 * page, which left /[lang]/projets/[slug] and /[lang]/actualites/[slug] with
 * zero prerendered paths. See lib/i18n/static-params.ts.
 */

export async function generateMetadata({ params }: LayoutProps<"/[lang]">): Promise<Metadata> {
	const { lang } = await params;
	if (!isLocale(lang)) return {};

	const dictionary = getDictionary(lang);

	return {
		title: {
			default: dictionary.meta.home.title,
			// Page titles read "Projets · Association Asselda".
			template: `%s · ${dictionary.meta.siteName}`,
		},
		description: dictionary.meta.home.description,
		applicationName: dictionary.meta.siteName,
		openGraph: {
			type: "website",
			siteName: dictionary.meta.siteName,
			locale: localeTags[lang],
			title: dictionary.meta.home.title,
			description: dictionary.meta.home.description,
		},
		alternates: {
			canonical: localizePath("/", lang),
			// Tells search engines the three locales are translations of each other.
			languages: Object.fromEntries(
				locales.map((locale) => [localeTags[locale], localizePath("/", locale)]),
			),
		},
		icons: { icon: "/favicon.ico" },
	};
}

export default async function LocaleLayout({ children, params }: LayoutProps<"/[lang]">) {
	const { lang } = await params;

	// A path such as /de/projets must 404 rather than silently render French.
	if (!isLocale(lang)) notFound();

	const locale = lang as Locale;
	const dictionary = getDictionary(locale);

	return (
		<html
			lang={localeTags[locale]}
			dir={getDirection(locale)}
			className={fontVariables}
			suppressHydrationWarning>
			<body className="flex min-h-dvh flex-col">
				<a
					href="#main-content"
					className="sr-only-focusable absolute start-4 top-4 z-50 rounded-pill bg-forest-800 px-5 py-3 text-sm font-semibold text-white shadow-card-hover">
					{dictionary.nav.skipToContent}
				</a>

				<Header locale={locale} dictionary={dictionary} />

				<main id="main-content" className="flex-1">
					{children}
				</main>

				<Footer locale={locale} dictionary={dictionary} />
			</body>
		</html>
	);
}
